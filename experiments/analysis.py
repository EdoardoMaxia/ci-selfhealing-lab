MODEL_ORDER: list[str] = []
COLORS: dict[str, str] = {}


def discover_results(results_dir: Path = RESULTS_DIR):
    """
    Recursively scans results_dir looking for the benchmark CSVs
    and parses them based on the file name pattern
    (benchmark_{YYYYMMDD}_{HHMMSS}_{model_id}_{condition}.csv).

    For the same (model_id, condition), keeps only the most recent file
    (highest timestamp in the name).

    Returns (files, model_order, colors):
      - files: dict {(display_name, condition): Path}
               condition is "no_memory" or "memory"
      - model_order: list of display names, preferred order + rest alphabetical
      - colors: dict {display_name: hex color}
    """
    latest = {}  # (model_id, condition) -> (timestamp_str, Path)
    skipped = []

    for csv_path in sorted(results_dir.rglob("*.csv")):
        m = FILENAME_RE.match(csv_path.name)
        if not m:
            skipped.append(csv_path)
            continue
        date_str, time_str, model_id, cond_raw = m.groups()
        condition = "no_memory" if cond_raw == "nomemory" else "memory"
        timestamp = date_str + time_str
        key = (model_id, condition)
        if key not in latest or timestamp > latest[key][0]:
            latest[key] = (timestamp, csv_path)

    print("\nCSV files found:")
    files = {}
    for (model_id, condition), (timestamp, path) in sorted(latest.items()):
        label = DISPLAY_NAMES.get(model_id, model_id)
        files[(label, condition)] = path
        try:
            shown_path = path.relative_to(results_dir)
        except ValueError:
            shown_path = path
        print(f"  {shown_path}  →  model_id='{model_id}' → '{label}', "
              f"condition='{condition}' (timestamp {timestamp})")

    if skipped:
        print(f"  ({len(skipped)} .csv files ignored: name does not match the pattern)")
        for path in skipped:
            print(f"    - {path}")

    labels_found = sorted({label for (label, _cond) in files.keys()})
    preferred = [m for m in PREFERRED_MODEL_ORDER if m in labels_found]
    rest      = sorted(m for m in labels_found if m not in PREFERRED_MODEL_ORDER)
    model_order = preferred + rest

    colors = {}
    fallback_i = 0
    for label in model_order:
        if label in KNOWN_COLORS:
            colors[label] = KNOWN_COLORS[label]
        else:
            colors[label] = FALLBACK_PALETTE[fallback_i % len(FALLBACK_PALETTE)]
            fallback_i += 1

    return files, model_order, colors


# ══════════════════════════════════════════════════════════════
# LOADING
# ══════════════════════════════════════════════════════════════

def load_all_data(results_dir: Path = RESULTS_DIR) -> pd.DataFrame:
    global MODEL_ORDER, COLORS
    files, MODEL_ORDER, COLORS = discover_results(results_dir)

    dfs = []
    for (model, condition), path in files.items():
        if not path.exists():
            print(f"⚠️  File not found: {path}")
            continue
        df = pd.read_csv(path)

        # Cases with final_status=="excluded" (non-injectable target, see
        # CHANGELOG_DATASET.md) are not real attempts: they must be excluded from
        # the denominator of SR / Router F1 / attempt distribution, but they
        # should no longer appear in the current CSVs (dataset 150/150 active).
        if "final_status" in df.columns:
            n_excluded = int((df["final_status"] == "excluded").sum())
            if n_excluded > 0:
                df = df[df["final_status"] != "excluded"].reset_index(drop=True)
                print(f"  ⚠️  {n_excluded} 'excluded' cases removed from {path.name} "
                      f"(not counted in SR/F1/attempt distribution)")

        df["model_label"] = model
        df["condition"]   = condition
        dfs.append(df)
        print(f"✅ Loaded: {model} / {condition} — {len(df)} rows  ({path.name})")

    if not dfs:
        raise SystemExit(f"No valid CSV found in: {results_dir}")

    combined = pd.concat(dfs, ignore_index=True)
    print(f"\nTotal dataset: {len(combined)} rows\n")
    return combined


