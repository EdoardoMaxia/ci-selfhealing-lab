def print_summary_table(df: pd.DataFrame):
    """
    Summary table.
    - Router Macro F1 (not Recall)
    - SR by difficulty
    - Attempt distribution
    - JSON parse failure: always 0, handled by the fallback (not reported in the paper since it is not a relevant figure)
    """
    data   = df[df["condition"] == "no_memory"]
    models = MODEL_ORDER

    print("\n" + "=" * 100)
    print("SUMMARY TABLE — exact values (no rounding)")
    print("=" * 100)
    print(f"{'Model':<22} {'SR%':>10} {'Dep%':>10} {'Test%':>10} {'Conf%':>10}"
          f"  {'Easy (n/N %)':>16}  {'Med (n/N %)':>16}  {'Hard (n/N %)':>16}"
          f"  {'F1-R%':>10}  {'AvgLat':>10}")
    print("-" * 100)

    for model in models:
        md = data[data["model_label"] == model]
        if len(md) == 0:
            continue
        # No rounding — 4 decimals
        sr   = md["success"].mean() * 100
        dep  = md[md["category"] == "dependency"]["success"].mean() * 100
        test = md[md["category"] == "test"]["success"].mean() * 100
        conf = md[md["category"] == "config"]["success"].mean() * 100
        lat  = md["latency_sec"].mean()

        # Exact fractions
        e = md[md["difficulty"] == "easy"]
        m = md[md["difficulty"] == "medium"]
        h = md[md["difficulty"] == "hard"]
        easy_s = f"{int(e['success'].sum())}/{len(e)} {e['success'].mean()*100:.4f}%"
        med_s  = f"{int(m['success'].sum())}/{len(m)} {m['success'].mean()*100:.4f}%"
        hard_s = f"{int(h['success'].sum())}/{len(h)} {h['success'].mean()*100:.4f}%"

        router_f1 = compute_f1_macro(md)

        print(f"{model:<22}"
              f" {sr:>9.4f}%"
              f" {dep:>9.4f}%"
              f" {test:>9.4f}%"
              f" {conf:>9.4f}%"
              f"  {easy_s:>16}"
              f"  {med_s:>16}"
              f"  {hard_s:>16}"
              f"  {router_f1:>9.4f}%"
              f"  {lat:>9.2f}s")

    print("=" * 100)

    # Ablation
    print("\nABLATION STUDY — Impact of the episodic memory")
    print("=" * 65)
    print(f"{'Model':<22} {'SR no_mem%':>14} {'SR memory%':>14} {'Delta':>12}")
    print("-" * 65)
    for model in models:
        nm = df[(df["model_label"] == model) & (df["condition"] == "no_memory")]
        mm = df[(df["model_label"] == model) & (df["condition"] == "memory")]
        if len(nm) == 0 or len(mm) == 0:
            continue
        sr_no  = nm["success"].mean() * 100
        sr_mem = mm["success"].mean() * 100
        delta  = sr_mem - sr_no
        sign   = "▲" if delta > 0 else "▼" if delta < 0 else "="
        print(f"{model:<22}"
              f" {sr_no:>13.4f}%"
              f" {sr_mem:>13.4f}%"
              f"  {sign}{abs(delta):>9.4f}%")
    print("=" * 65)

    # Attempt distribution
    print("\nATTEMPT DISTRIBUTION")
    for cond_key, cond_label in [("no_memory", "WITHOUT memory"),
                                  ("memory",    "WITH memory")]:
        cdata = df[df["condition"] == cond_key]
        print(f"\n  {cond_label}")
        print("  " + "=" * 82)
        print(f"  {'Model':<22}"
              f" {'T1 n/N (%)':>16}"
              f" {'T2 n/N (%)':>16}"
              f" {'T3 n/N (%)':>16}"
              f" {'ESC n/N (%)':>16}")
        print("  " + "-" * 82)
        for model in models:
            md = cdata[cdata["model_label"] == model]
            n  = len(md)
            if n == 0:
                continue
            t1  = len(md[(md["success"] == 1) & (md["fix_attempt"] == 1)])
            t2  = len(md[(md["success"] == 1) & (md["fix_attempt"] == 2)])
            t3  = len(md[(md["success"] == 1) & (md["fix_attempt"] == 3)])
            esc = len(md[md["success"] == 0])
            print(f"  {model:<22}"
                  f" {t1}/{n} ({t1/n*100:.4f}%)"
                  f"  {t2}/{n} ({t2/n*100:.4f}%)"
                  f"  {t3}/{n} ({t3/n*100:.4f}%)"
                  f"  {esc}/{n} ({esc/n*100:.4f}%)")
        print("  " + "=" * 82)

    # Dynamic T3 note — with the current dataset the fix at the 3rd attempt can
    # appear even without episodic memory (the router can converge at
    # T3 without RAG); here we report what the data actually show, instead of
    # statically assuming T3=0% without memory.
    no_mem_data = df[df["condition"] == "no_memory"]
    t3_no_mem = {}
    for model in models:
        md = no_mem_data[no_mem_data["model_label"] == model]
        n = len(md)
        if n == 0:
            continue
        t3 = len(md[(md["success"] == 1) & (md["fix_attempt"] == 3)])
        if t3 > 0:
            t3_no_mem[model] = (t3, n)

    print()
    if t3_no_mem:
        print("T3 NOTE (without memory): fixes at attempt 3 observed even without RAG:")
        for model, (t3, n) in t3_no_mem.items():
            print(f"  - {model}: {t3}/{n} ({t3/n*100:.4f}%)")
    else:
        print("T3=0% NOTE (no_memory): no fix at attempt 3 observed without")
        print("  episodic memory in this dataset.")

    # JSON parse failure
    print("\nJSON PARSE FAILURE RATE")
    print("=" * 60)
    if "json_parse_fail" in data.columns:
        for model in models:
            md = data[data["model_label"] == model]
            jf = int(md["json_parse_fail"].sum())
            print(f"  {model}: {jf}/{len(md)} ({jf/len(md)*100:.4f}%)")


