"""

The Fix Executor is the LangGraph node that orchestrates everything:
- reads the file modified by the agent;
- uploads it to GitHub;
- waits for the CI and updates the state with the actual result.

"""

import os
from pathlib import Path
from datetime import datetime
from dotenv import load_dotenv
from agent.github.client import (
    get_repo, create_branch, commit_file,
    wait_for_ci, create_pull_request
)


load_dotenv()


# File that each agent can modify
AGENT_FILE_MAP = {
    "dependency" : "requirements.txt",
    "test" :       "tests/test_calculator.py",
    "config" :     ".github/workflows/ci.yml"
}



def build_branch_name(state: dict) -> str:
    """Generates a unique branch name for the fix."""
    category = state.get("error_category", "unknown")
    sha_short = state.get("commit_sha", "xxxxx")[:7]
    attempt = state.get("attempt_number", 1) - 1 # -1 because it was already incremented
    timestamp = datetime.now().strftime("%H%M%S")
    return f"fix/ai-{category}-{sha_short}-t{attempt}-{timestamp}"



def build_pr_body(state: dict) -> str:
    """Generates the PR body with the full report."""
    history = state.get("attempts_history", [])

    history_text = "\n".join([
        f"- **Attempt {h['attempt']}**: {h['fix_applied']}\n  ```diff\n  {h['fix_diff']}\n  ```"
        for h in history
    ])

    return f"""## 🤖 Self-Healing CI — Automatic Fix

    ### Detected error
    - **Category**: `{state.get('error_category', 'unknown')}`
    - **Failed job**: `{state.get('ci_job_name', 'N/A')}`
    - **Commit**: `{state.get('commit_sha', 'N/A')[:8]}`
    - **Classification confidence**: {state.get('error_confidence', 0):.0%}

    ### Router reasoning
    {state.get('router_reasoning', 'N/A')}

    ### Applied fixes
    {history_text}

    ### Note
    - Fix automatically generated by the Self-Healing CI system
    - Verified: CI green ✅ after applying it
    - Requires human review before merging

    > *Generated by Self-Healing CI Agent*
    """



def fix_executor_node(state: dict) -> dict:
    """
    Fix Executor node: after an agent has modified the file locally,
    this node uploads it to GitHub, waits for the CI and updates the state.
    """
    repo_name = state.get("repo_name")
    repo_path = state.get("repo_path", ".")
    category  = state.get("error_category", "dependency")

    print(f"\n🔧 Fix Executor started for category: {category}")
    print(f"🔍 DEBUG modified_file = {repr(state.get('modified_file'))}")

    # 1. Identify which file was modified
    if category == "test" and state.get("modified_file"):
        file_path = state["modified_file"]
        # Convert the absolute path into one relative to the repo
        file_path = file_path.replace(str(Path(repo_path).resolve()), "").lstrip("/\\")
    else:
        file_path = AGENT_FILE_MAP.get(category, "requirements.txt")

    print(f"🔍 DEBUG final file_path = {repr(file_path)}")
        
    local_file = Path(repo_path) / file_path

    if not local_file.exists():
        print(f"⚠️  File {file_path} not found locally")
        return {"ci_fixed": False}

    new_content = local_file.read_text(encoding="utf-8")

    # 2. Connect to the GitHub repo
    repo       = get_repo(repo_name) #type: ignore
    main_sha   = repo.get_branch("main").commit.sha
    branch_name = build_branch_name(state)

    # 3. Create the branch and commit
    create_branch(repo, main_sha, branch_name)
    commit_message = (
        f"fix(ai): auto-fix {category} error\n\n"
        f"Original commit: {state.get('commit_sha','')[:8]}\n"
        f"Attempt: {state.get('attempt_number', 1) - 1}/3\n"
        f"[self-healing-ci]"
    )
    commit_file(repo, branch_name, file_path, new_content, commit_message)

    # 4. Wait for the CI result
    ci_passed = wait_for_ci(repo, branch_name, timeout_sec=300)

    # 5. Update the state with the actual result
    updates = {"ci_fixed": ci_passed, "fix_branch": branch_name}

    if ci_passed:
        # CI green: the PR will be created by the create_pr node
        updates["fix_branch"] = branch_name
        print("✅ CI green — ready for the PR")
    else:
        print("❌ CI still red")

    return updates